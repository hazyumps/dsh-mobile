class Ctx:
    __slots__ = ("top_name", "path", "schema_rel", "doc", "label")

    def __init__(self, top_name, path, schema_rel, doc, label=None):
        self.top_name = top_name
        self.path = path
        self.schema_rel = schema_rel
        self.doc = doc
        # Documentation-only label, used where a union alternative shares its
        # JSON location with the union and the raw pointer would be ambiguous.
        self.label = label

    @property
    def name(self) -> str:
        return self.top_name + "".join(pascal(p) for p in self.path)

    @property
    def symbol(self) -> str:
        return self.doc.get("x-dsh-typeSymbol", self.top_name)

    def child(self, token: str) -> "Ctx":
        return Ctx(self.top_name, self.path + [token], self.schema_rel, self.doc, None)


class Generator:
    def __init__(self):
        self.decls: dict[str, list[dict]] = {}
        self.manifest_models: list[dict] = []
        self.examples: dict[str, dict] = {}
        self.names: dict[str, str] = {}
        self.warnings: list[str] = []
        self.support_needed: set[str] = set()

    # -- io ---------------------------------------------------------------

    def load(self, schema_rel: str) -> dict:
        with open(os.path.join(PROTOCOL, schema_rel), "r", encoding="utf-8") as handle:
            return json.load(handle)

    # -- naming -----------------------------------------------------------

    def claim(self, name: str, where: str) -> None:
        if self.names.get(name) == where:
            return
        if name in EXISTING_SWIFT_TYPES:
            raise SchemaError(
                f"{where}: generated type {name} collides with a hand-written type"
            )
        if name in self.names:
            raise SchemaError(
                f"{where}: generated type {name} already claimed by {self.names[name]}"
            )
        self.names[name] = where

    def add_decl(self, top: str, decl: dict, example: Example) -> None:
        decl["example"] = example
        self.decls[top].append(decl)

    # -- per schema -------------------------------------------------------

    def generate_schema(self, schema_rel: str, doc: dict) -> None:
        top = swift_name_for_symbol(doc["x-dsh-typeSymbol"])
        self.claim(top, schema_rel)
        self.decls.setdefault(top, [])
        ctx = Ctx(top, [], schema_rel, doc)
        type_expr, nullable, example = self.resolve(doc, ctx, "")

        declared = {d["name"] for d in self.decls[top]}
        if top not in declared:
            self.add_decl(
                top,
                {
                    "name": top,
                    "kind": "typealias",
                    "nullable": nullable,
                    "mayBeAbsent": bool(doc.get("x-dsh-mayBeAbsent")),
                    "swift": alias_swift(top, type_expr, nullable, ctx),
                },
                example,
            )
        else:
            for decl in self.decls[top]:
                if decl["name"] == top:
                    decl["nullable"] = nullable
                    decl["mayBeAbsent"] = bool(doc.get("x-dsh-mayBeAbsent"))

        # A declaration sits at a JSON pointer in the schema's example file only
        # where the example instance actually reaches it. A union alternative the
        # example does not instantiate still gets a generated type — and its own
        # example value — but no file pointer.
        reachable: set[int] = set()

        def mark(node: Example):
            reachable.add(id(node))
            for _segment, _token, child, _required in node.children:
                mark(child)

        mark(example)

        self.examples[schema_rel] = {
            "top": top,
            "nullable": nullable,
            "example": example,
            "symbol": doc["x-dsh-typeSymbol"],
        }

        stem = schema_stem(schema_rel)
        for decl in self.decls[top]:
            node = decl["example"]
            entry = {
                "swiftType": decl["name"],
                "kind": decl["kind"],
                "typeSymbol": doc["x-dsh-typeSymbol"],
                "schema": schema_rel,
                "exampleFile": f"examples/{stem}.json",
                "examplePointer": node.pointer if id(node) in reachable else None,
                "example": node.value,
                "sourceFile": f"Generated/{top}.swift",
                "nullable": decl.get("nullable", False),
                "mayBeAbsent": decl.get("mayBeAbsent", False),
                "requiredPointers": required_pointers(node, node.pointer),
                "mutation": find_mutation(node, node.pointer),
            }
            self.manifest_models.append(entry)

    # -- the walk ---------------------------------------------------------

    def resolve(self, node, ctx: Ctx, pointer: str):
        """``(swift type expression, nullable, Example)`` for one schema node.

        The returned expression is never optional: a caller that needs a `?`
        appends it using the nullable flag.
        """
        reuse = REUSED_NODES.get((ctx.schema_rel, pointer))
        if reuse is not None:
            return reuse, False, Example(minimal_example(node), pointer=pointer)

        if is_json_value_ref(node) or is_json_value(node):
            return "JSONValue", False, Example(None, strict=False, pointer=pointer)

        if not isinstance(node, dict):
            raise SchemaError(f"{ctx.schema_rel}{pointer}: schema node is not an object")

        if node.get("not") == {} and len(node) == 1:
            self.support_needed.add("DSHNever")
            return "DSHNever", False, Example(None, strict=True, disjoint=0, pointer=pointer)

        if "anyOf" in node:
            return self.resolve_union(node, ctx, pointer)
        if "allOf" in node:
            return self.resolve_object(node, ctx, pointer)

        if "const" in node and "type" not in node:
            return self.resolve_const(node, pointer)

        kind = node.get("type")
        if kind == "string":
            return "String", False, Example("", strict=True, disjoint=0, pointer=pointer)
        if kind == "number":
            return "Int64", False, Example(1, strict=True, disjoint="mutation", pointer=pointer)
        if kind == "boolean":
            return "Bool", False, Example(True, strict=True, disjoint="mutation", pointer=pointer)
        if kind == "null":
            self.support_needed.add("DSHNull")
            return "DSHNull", False, Example(None, strict=True, disjoint=0, pointer=pointer)
        if kind == "array":
            item_pointer = join_pointer(pointer, "0")
            item_type, item_nullable, item_example = self.resolve(
                node["items"], ctx.child("Item"), item_pointer
            )
            del item_pointer
            element = item_type + ("?" if item_nullable else "")
            example = Example(
                [item_example.value],
                children=[(0, "Item", item_example, False)],
                strict=True,
                disjoint=0,
                pointer=pointer,
            )
            return f"[{element}]", False, example
        if kind == "object":
            has_fields = "properties" in node or "additionalProperties" in node
            if not has_fields:
                return "JSONValue", False, Example(None, strict=False, pointer=pointer)
            return self.resolve_object(node, ctx, pointer)

        if not node:
            return "JSONValue", False, Example(None, strict=False, pointer=pointer)

        raise SchemaError(f"{ctx.schema_rel}{pointer}: unhandled schema node {sorted(node)}")

    def resolve_const(self, node, pointer):
        value = node["const"]
        if value is None:
            return "DSHNull", False, Example(None, strict=True, disjoint=0, pointer=pointer)
        if isinstance(value, bool):
            return "Bool", False, Example(value, strict=True, disjoint=0, pointer=pointer)
        if isinstance(value, int):
            return "Int64", False, Example(value, strict=True, disjoint="mutation", pointer=pointer)
        if isinstance(value, str):
            return "String", False, Example(value, strict=True, disjoint=0, pointer=pointer)
        raise SchemaError(f"const of unhandled type {value!r} at {pointer}")

    # -- unions -----------------------------------------------------------

    def resolve_union(self, node, ctx: Ctx, pointer: str):
        members = node["anyOf"]
        nullable = any(is_null_const(m) for m in members)
        non_null = [m for m in members if not is_null_const(m)]
        if not non_null:
            return "DSHNull", False, Example(None, strict=True, disjoint=0, pointer=pointer)
        if len(non_null) == 1:
            inner_type, inner_nullable, inner_example = self.resolve(
                non_null[0], ctx, pointer
            )
            return inner_type, nullable or inner_nullable, inner_example

        if all(is_const(m) and isinstance(m["const"], str) for m in non_null):
            return self.enum_of_consts(non_null, ctx, pointer, nullable)

        discriminated = []
        for member in non_null:
            disc = discriminator_of(member)
            if disc is None:
                raise SchemaError(
                    f"{ctx.schema_rel}{pointer}: a union member has no string const "
                    "discriminator; general unions are not modelled"
                )
            discriminated.append(disc)

        keys = {key for key, _ in discriminated}
        values = [value for _, value in discriminated]
        if len(keys) != 1:
            raise SchemaError(
                f"{ctx.schema_rel}{pointer}: union members disagree on the "
                f"discriminator key: {sorted(keys)}"
            )
        if len(set(values)) != len(values):
            raise SchemaError(f"{ctx.schema_rel}{pointer}: duplicate discriminators {values}")
        return self.enum_of_variants(
            non_null, discriminated[0][0], discriminated, ctx, pointer, nullable
        )

    def enum_of_consts(self, members, ctx: Ctx, pointer: str, nullable: bool):
        name = ctx.name
        self.claim(name, f"{ctx.schema_rel}{pointer}")
        values = [m["const"] for m in members]
        cases = [(camel(value), value) for value in values]
        seen: dict[str, str] = {}
        for case, raw in cases:
            if case == CATCH_ALL:
                raise SchemaError(
                    f"{ctx.schema_rel}{pointer}: const {raw!r} sanitises onto the "
                    f"catch-all case name {CATCH_ALL!r}"
                )
            if case in seen:
                raise SchemaError(
                    f"{ctx.schema_rel}{pointer}: consts {seen[case]!r} and {raw!r} "
                    f"both name case {case!r}"
                )
            seen[case] = raw

        lines = [
            doc_comment(
                [
                    f"String union `{pointer or '/'}` of ``{ctx.symbol}``.",
                    "",
                    f"Open: an unrecognised value decodes to `.{CATCH_ALL}(_:)` instead of "
                    "failing (SPEC §5).",
                ]
            ),
            f"public enum {name}: Codable, Sendable, Hashable {{",
        ]
        for case, _raw in cases:
            lines.append(f"    case {swift_ident(case)}")
        lines.append(f"    case {CATCH_ALL}(String)")
        lines.append("")
        lines.append("    public init(rawValue: String) {")
        lines.append("        switch rawValue {")
        for case, raw in cases:
            lines.append(f"        case {json_string(raw)}: self = .{swift_ident(case)}")
        lines.append(f"        default: self = .{CATCH_ALL}(rawValue)")
        lines.append("        }")
        lines.append("    }")
        lines.append("")
        lines.append("    public var rawValue: String {")
        lines.append("        switch self {")
        for case, raw in cases:
            lines.append(f"        case .{swift_ident(case)}: {json_string(raw)}")
        lines.append(f"        case .{CATCH_ALL}(let value): value")
        lines.append("        }")
        lines.append("    }")
        lines.append("")
        lines.append("    public init(from decoder: any Decoder) throws {")
        lines.append(
            f"        self = {name}(rawValue: try decoder.singleValueContainer()"
            ".decode(String.self))"
        )
        lines.append("    }")
        lines.append("")
        lines.append("    public func encode(to encoder: any Encoder) throws {")
        lines.append("        var container = encoder.singleValueContainer()")
        lines.append("        try container.encode(rawValue)")
        lines.append("    }")
        lines.append("}")

        self.add_decl(
            ctx.top_name,
            {
                "name": name,
                "kind": "enum",
                "path": list(ctx.path),
                "nullable": nullable,
                "swift": "\n".join(lines) + "\n",
            },
            Example(values[0], strict=True, disjoint=0, pointer=pointer),
        )
        return name, nullable, Example(values[0], strict=True, disjoint=0, pointer=pointer)

    def enum_of_variants(self, members, key, discriminated, ctx: Ctx, pointer, nullable):
        name = ctx.name
        self.claim(name, f"{ctx.schema_rel}{pointer}")

        used: dict[str, str] = {}
        variants = []
        for member, (_key, value) in zip(members, discriminated):
            case = camel(value)
            if case == CATCH_ALL or case in used:
                raise SchemaError(
                    f"{ctx.schema_rel}{pointer}: variant case name {case!r} collides"
                )
            used[case] = value
            # A union member shares the union's JSON location: the discriminator
            # is a key of the same object, so no JSON nesting happens here.
            member_ctx = ctx.child(pascal(value))
            member_ctx.label = f"{pointer}/{case}"
            member_type, _member_nullable, member_example = self.resolve(
                member, member_ctx, pointer
            )
            variants.append((case, value, member_type, member_example))

        lines = [
            doc_comment(
                [
                    f"Discriminated union `{pointer or '/'}` of ``{ctx.symbol}``, "
                    f"selected by the wire key `{key}`.",
                    "",
                    f"Open: an unrecognised discriminator decodes to "
                    f"`.{CATCH_ALL}(type:value:)` instead of failing (SPEC §5). A missing "
                    "discriminator fails — the union cannot be classified without it.",
                ]
            ),
            f"public enum {name}: Codable, Sendable, Hashable {{",
        ]
        for case, _raw, member_type, _ex in variants:
            lines.append(f"    case {swift_ident(case)}({member_type})")
        lines.append(f"    case {CATCH_ALL}(type: String, value: JSONValue)")
        lines.append("")
        lines.append("    /// The wire key whose value selects the member.")
        lines.append(f"    public static let discriminatorKey = {json_string(key)}")
        lines.append("")
        lines.append("    private enum DiscriminatorKey: String, CodingKey {")
        lines.append(f"        case value = {json_string(key)}")
        lines.append("    }")
        lines.append("")
        lines.append("    public init(from decoder: any Decoder) throws {")
        lines.append("        let container = try decoder.container(keyedBy: DiscriminatorKey.self)")
        lines.append("        let tag = try container.decode(String.self, forKey: .value)")
        lines.append("        switch tag {")
        for case, raw, member_type, _ex in variants:
            lines.append(
                f"        case {json_string(raw)}: self = .{swift_ident(case)}"
                f"(try {member_type}(from: decoder))"
            )
        lines.append(
            f"        default: self = .{CATCH_ALL}(type: tag, value: try JSONValue(from: decoder))"
        )
        lines.append("        }")
        lines.append("    }")
        lines.append("")
        lines.append("    public func encode(to encoder: any Encoder) throws {")
        lines.append("        switch self {")
        for case, _raw, _type, _ex in variants:
            lines.append(
                f"        case .{swift_ident(case)}(let value): try value.encode(to: encoder)"
            )
        lines.append(f"        case .{CATCH_ALL}(_, let value): try value.encode(to: encoder)")
        lines.append("        }")
        lines.append("    }")
        lines.append("}")

        chosen_case, _chosen_raw, _chosen_type, chosen_example = variants[0]
        # A union member shares the union's own JSON location — the discriminator
        # is a key of the same object — so the node keeps the union's JSON pointer
        # and only the declaration name path descends into the case.
        example = Example(
            chosen_example.value,
            children=[(None, pascal(chosen_case), chosen_example, False)],
            strict=True,
            disjoint=0,
            pointer=pointer,
        )
        self.add_decl(
            ctx.top_name,
            {
                "name": name,
                "kind": "enum",
                "path": list(ctx.path),
                "nullable": nullable,
                "swift": "\n".join(lines) + "\n",
            },
            example,
        )
        return name, nullable, example

    # -- objects ----------------------------------------------------------

    def resolve_object(self, node, ctx: Ctx, pointer: str):
        properties, required, extras = flatten_object(node)
        if not properties and extras is None:
            return "JSONValue", False, Example(None, strict=False, pointer=pointer)
        if not properties and extras is not None:
            # `record(string(), V)` with nothing beside it: a plain dictionary.
            extras_pointer = join_pointer(pointer, EXTRA_KEY)
            value_type, _n, extras_example = self.resolve(
                extras, ctx.child("AdditionalProperty"), extras_pointer
            )
            example = Example(
                {EXTRA_KEY: extras_example.value},
                children=[(EXTRA_KEY, "AdditionalProperty", extras_example, False)],
                strict=True,
                disjoint=0,
                pointer=pointer,
            )
            return f"[String: {value_type}]", False, example

        name = ctx.name
        self.claim(name, f"{ctx.schema_rel}{pointer}")

        fields = []
        example = Example({}, strict=True, disjoint=0, pointer=pointer)
        for key in properties:
            prop_pointer = join_pointer(pointer, key)
            type_expr, nullable, prop_example = self.resolve(
                properties[key], ctx.child(pascal(key)), prop_pointer
            )
            is_required = key in required
            optional = nullable or not is_required
            if optional:
                type_expr += "?"
            fields.append(
                {
                    "jsonKey": key,
                    "swiftName": camel(key),
                    "type": type_expr,
                    "optional": optional,
                    "enforced": is_required and not nullable,
                }
            )
            example.value[key] = prop_example.value
            example.children.append(
                (key, pascal(key), prop_example, is_required and not nullable)
            )

        extras_type = None
        if extras is not None:
            extras_pointer = join_pointer(pointer, EXTRA_KEY)
            extras_type, _n, extras_example = self.resolve(
                extras, ctx.child("AdditionalProperty"), extras_pointer
            )
            example.value[EXTRA_KEY] = extras_example.value
            example.children.append(
                (EXTRA_KEY, "AdditionalProperty", extras_example, False)
            )
            example.strict = False
            self.support_needed.add("DSHDynamicCodingKey")

        lines = [doc_comment(self.object_doc(ctx, pointer, extras_type))]
        lines.append(f"public struct {name}: Codable, Sendable, Hashable {{")
        for field in fields:
            lines.append(f"    public var {swift_ident(field['swiftName'])}: {field['type']}")
        if extras_type is not None:
            lines.append("")
            lines.append(
                "    /// Every key the static object above does not name. The DSL writes this"
            )
            lines.append(
                "    /// object as `intersection(object({...}), record(string(), JsonValue))` and"
            )
            lines.append(
                "    /// the projection registry is open, so an unnamed projection has to"
            )
            lines.append("    /// survive a decode rather than be dropped.")
            lines.append(f"    public var additionalProperties: [String: {extras_type}]")
        lines.append("")
        case_iterable = ", CaseIterable" if extras_type is not None else ""
        lines.append(f"    enum CodingKeys: String, CodingKey{case_iterable} {{")
        for field in fields:
            lines.append(
                f"        case {swift_ident(field['swiftName'])} = {json_string(field['jsonKey'])}"
            )
        if extras_type is not None:
            lines.append("        case additionalProperties")
        lines.append("    }")
        lines.append("")

        init_params = []
        for field in fields:
            default = " = nil" if field["optional"] else ""
            init_params.append(
                f"{swift_ident(field['swiftName'])}: {field['type']}{default}"
            )
        if extras_type is not None:
            init_params.append(f"additionalProperties: [String: {extras_type}] = [:]")
        if init_params:
            lines.append("    public init(")
            for index, param in enumerate(init_params):
                comma = "," if index < len(init_params) - 1 else ""
                lines.append(f"        {param}{comma}")
            lines.append("    ) {")
        else:
            lines.append("    public init() {")
        for field in fields:
            ident = swift_ident(field["swiftName"])
            lines.append(f"        self.{ident} = {ident}")
        if extras_type is not None:
            lines.append("        self.additionalProperties = additionalProperties")
        lines.append("    }")

        if extras_type is not None:
            lines.append("")
            lines.append("    public init(from decoder: any Decoder) throws {")
            if fields:
                lines.append(
                    "        let container = try decoder.container(keyedBy: CodingKeys.self)"
                )
            for field in fields:
                ident = swift_ident(field["swiftName"])
                bare = field["type"].rstrip("?")
                if field["optional"]:
                    if field["type"].endswith("?"):
                        lines.append(
                            f"        self.{ident} = try container.decodeIfPresent("
                            f"{bare}.self, forKey: .{ident})"
                        )
                    else:
                        lines.append(
                            f"        self.{ident} = try container.decodeIfPresent("
                            f"{bare}.self, forKey: .{ident})"
                        )
                else:
                    lines.append(
                        f"        self.{ident} = try container.decode("
                        f"{bare}.self, forKey: .{ident})"
                    )
            lines.append(
                "        let known = Set("
                "CodingKeys.allCases.filter { $0 != .additionalProperties }"
                ".map(\\.stringValue))"
            )
            lines.append(f"        var extras: [String: {extras_type}] = [:]")
            lines.append(
                "        let dynamic = try decoder.container(keyedBy: DSHDynamicCodingKey.self)"
            )
            lines.append(
                "        for key in dynamic.allKeys where !known.contains(key.stringValue) {"
            )
            lines.append(
                f"            extras[key.stringValue] = try dynamic.decode("
                f"{extras_type}.self, forKey: key)"
            )
            lines.append("        }")
            lines.append("        self.additionalProperties = extras")
            lines.append("    }")
            lines.append("")
            lines.append("    public func encode(to encoder: any Encoder) throws {")
            if fields:
                lines.append(
                    "        var container = encoder.container(keyedBy: CodingKeys.self)"
                )
            for field in fields:
                ident = swift_ident(field["swiftName"])
                if field["optional"]:
                    lines.append(f"        try container.encodeIfPresent({ident}, forKey: .{ident})")
                else:
                    lines.append(f"        try container.encode({ident}, forKey: .{ident})")
            lines.append(
                "        var dynamic = encoder.container(keyedBy: DSHDynamicCodingKey.self)"
            )
            lines.append(
                "        for (key, value) in additionalProperties.sorted(by: { $0.key < $1.key }) {"
            )
            lines.append("            try dynamic.encode(value, forKey: DSHDynamicCodingKey(key))")
            lines.append("        }")
            lines.append("    }")

        lines.append("}")

        self.add_decl(
            ctx.top_name,
            {
                "name": name,
                "kind": "struct",
                "path": list(ctx.path),
                "nullable": False,
                "swift": "\n".join(lines) + "\n",
            },
            example,
        )
        return name, False, example

    def object_doc(self, ctx: Ctx, pointer: str, extras_type) -> list[str]:
        shown = ctx.label if ctx.label is not None else (pointer or "/")
        lines = [f"Object `{shown}` of ``{ctx.symbol}``."]
        lines.extend(used_by_lines(ctx.doc))
        if extras_type is None:
            lines.append("")
            lines.append(
                "Unknown keys are ignored on decode. Requests are closed on the wire even "
                "though the emitted schema does not say so (Protocol/README.md)."
            )
        return lines


# --------------------------------------------------------------------------
# Formatting helpers
# --------------------------------------------------------------------------


def json_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def schema_stem(schema_rel: str) -> str:
    return os.path.basename(schema_rel)[: -len(".json")]


def used_by_lines(doc: dict) -> list[str]:
    used = doc.get("x-dsh-usedBy") or []
    if not used:
        return []
    return ["Used by: " + ", ".join(f"`{u}`" for u in used) + "."]


def doc_comment(lines: list[str]) -> str:
    """Doc comment from paragraph lines; an empty string is a blank `///` line."""
    out = []
    for line in lines:
        out.append("///" if line == "" else f"/// {line}")
    return "\n".join(out)


def alias_swift(name: str, target: str, nullable: bool, ctx: Ctx) -> str:
    lines = [
        doc_comment(
            [
                f"``{ctx.symbol}`` — a bare {target} on the wire.",
                *used_by_lines(ctx.doc),
                ""
                if used_by_lines(ctx.doc)
                else "",
                "The schema also admits JSON `null`; callers pair this with `?`."
                if nullable
                else "",
            ]
        ),
        f"public typealias {name} = {target}",
    ]
    return "\n".join(lines) + "\n"


SUPPORT_TYPES = {
    "DSHDynamicCodingKey": '''/// A coding key for a JSON object whose key set the schema does not close.
///
/// Generated for objects the DSL writes as
/// `intersection(object({...}), record(string(), JsonValue))`, where any key the
/// static object does not name is still valid.
struct DSHDynamicCodingKey: CodingKey, Hashable {
    let stringValue: String
    let intValue: Int?

    init(_ stringValue: String) {
        self.stringValue = stringValue
        self.intValue = nil
    }

    init?(stringValue: String) {
        self.stringValue = stringValue
        self.intValue = nil
    }

    init?(intValue: Int) {
        self.stringValue = String(intValue)
        self.intValue = intValue
    }
}
''',
    "DSHNull": '''/// A JSON value that must be `null`.
///
/// The DSL's `_instanceof(Uint8Array)` translates to `{"type":"null"}`: the JSON
/// field really is null and the bytes ride out-of-band in the envelope's
/// `attachments` (Protocol/README.md). No V1 endpoint on this surface reaches it.
public struct DSHNull: Codable, Sendable, Hashable {
    public init() {}

    public init(from decoder: any Decoder) throws {
        let container = try decoder.singleValueContainer()
        guard container.decodeNil() else {
            throw DecodingError.dataCorruptedError(
                in: container,
                debugDescription: "Expected JSON null"
            )
        }
    }

    public func encode(to encoder: any Encoder) throws {
        var container = encoder.singleValueContainer()
        try container.encodeNil()
    }
}
''',
    "DSHNever": '''/// A JSON value no instance can satisfy — the DSL's `never()`.
///
/// Decoding always fails, which is what `{"not":{}}` means. No V1 endpoint on
/// this surface reaches it.
public struct DSHNever: Codable, Sendable, Hashable {
    public init() {}

    public init(from decoder: any Decoder) throws {
        let container = try decoder.singleValueContainer()
        throw DecodingError.dataCorruptedError(
            in: container,
            debugDescription: "never() accepts no value"
        )
    }

    public func encode(to encoder: any Encoder) throws {
        throw EncodingError.invalidValue(
            self,
            EncodingError.Context(
                codingPath: encoder.codingPath,
                debugDescription: "never() accepts no value"
            )
        )
    }
}
''',
}


