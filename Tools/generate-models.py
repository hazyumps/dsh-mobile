class SchemaError(Exception):
    pass


def is_null_const(node) -> bool:
    return isinstance(node, dict) and "const" in node and node["const"] is None


def is_const(node) -> bool:
    return isinstance(node, dict) and "const" in node


def ref_name(node) -> str | None:
    if isinstance(node, dict) and isinstance(node.get("$ref"), str):
        return node["$ref"].rsplit("/", 1)[-1]
    return None


def is_json_value_ref(node) -> bool:
    name = ref_name(node)
    return bool(name) and name.startswith("JsonValueRemoteCodec")


def is_json_value(node) -> bool:
    """The recursive JSON-value union the DSL spells `JsonValueRemoteCodec$schema*`.

    Matches a `$ref` to one of those `$defs` and the same shape written inline
    (the extractor inlines one level before it starts emitting `$ref`s).
    """
    if is_json_value_ref(node):
        return True
    if not isinstance(node, dict) or "anyOf" not in node:
        return False
    kinds = set()
    for member in node["anyOf"]:
        if is_const(member):
            value = member["const"]
            if value is None:
                kinds.add("null")
            elif isinstance(value, bool):
                kinds.add("bool")
            else:
                return False
        elif isinstance(member, dict) and member.get("type") == "string":
            kinds.add("string")
        elif isinstance(member, dict) and member.get("type") == "number":
            kinds.add("number")
        elif isinstance(member, dict) and member.get("type") == "boolean":
            kinds.add("bool")
        elif (
            isinstance(member, dict)
            and member.get("type") == "array"
            and is_json_value(member.get("items", {}))
        ):
            kinds.add("array")
        elif (
            isinstance(member, dict)
            and member.get("type") == "object"
            and is_json_value(member.get("additionalProperties", {}))
        ):
            kinds.add("object")
        else:
            return False
    return kinds == {"null", "string", "number", "bool", "array", "object"}


def flatten_object(node: dict):
    """Merge an object schema (and any `allOf` members) into one field set.

    Returns ``(properties, required, extras_node)``: an ordered mapping of JSON
    key to subschema, the required keys, and the value schema of an open
    `record(...)` companion (or ``None``).
    """
    properties: dict[str, dict] = {}
    required: list[str] = []
    extras = None

    def absorb(n):
        nonlocal extras
        if not isinstance(n, dict):
            raise SchemaError(f"allOf member is not an object schema: {n!r}")
        for member in n.get("allOf", []) or []:
            absorb(member)
        for key, value in (n.get("properties") or {}).items():
            properties.setdefault(key, value)
        for key in n.get("required") or []:
            if key not in required:
                required.append(key)
        if "additionalProperties" in n:
            ap = n["additionalProperties"]
            if ap is True:
                extras = {}
            elif isinstance(ap, dict):
                extras = ap

    absorb(node)
    return properties, required, extras


def discriminator_of(node: dict):
    """`(key, const)` for a union member, or ``None`` when it cannot be classified."""
    try:
        properties, _, _ = flatten_object(node)
    except SchemaError:
        return None
    for preferred in ("type", "kind"):
        if preferred in properties and is_const(properties[preferred]):
            value = properties[preferred]["const"]
            if isinstance(value, str):
                return preferred, value
    found = None
    for key, schema in properties.items():
        if is_const(schema) and isinstance(schema["const"], str):
            if found is not None:
                return None
            found = (key, schema["const"])
    return found


def merge_examples(a, b):
    """Merge two example JSON values, preferring the first."""
    if isinstance(a, dict) and isinstance(b, dict):
        out = dict(b)
        out.update(a)
        return out
    if isinstance(a, list) and isinstance(b, list):
        return a or b
    if a is None:
        return b
    return a


def minimal_example(node, depth=0):
    """A minimal instance satisfying a schema node, without emitting types.

    Used where a node is replaced by a hand-written Swift type: the example has
    to stay valid for the schema, but the hand-written type owns the optionality
    and a richer instance would test that type rather than this generator.
    """
    if depth > 12:
        return None
    if is_json_value_ref(node) or is_json_value(node):
        return None
    if not isinstance(node, dict):
        return None
    if "anyOf" in node:
        members = [m for m in node["anyOf"] if not is_null_const(m)]
        if not members:
            return None
        return minimal_example(members[0], depth + 1)
    if "allOf" in node:
        properties, required, _ = flatten_object(node)
        return {
            key: minimal_example(properties[key], depth + 1)
            for key in required
            if key in properties
        }
    if "const" in node:
        return node["const"]
    kind = node.get("type")
    if kind == "string":
        return ""
    if kind == "number":
        return 1
    if kind == "boolean":
        return True
    if kind == "null":
        return None
    if kind == "array":
        return [minimal_example(node.get("items", {}), depth + 1)]
    if kind == "object":
        if "properties" not in node and "additionalProperties" not in node:
            return None
        properties, required, extras = flatten_object(node)
        out = {
            key: minimal_example(properties[key], depth + 1)
            for key in required
            if key in properties
        }
        if extras is not None:
            out[EXTRA_KEY] = minimal_example(extras, depth + 1)
        return out
    return None


