#!/usr/bin/env python3
"""Derive the iPhone client's typed DTOs for the V1 remote surface.

Inputs (read only):

* ``Protocol/endpoints.json`` — the descriptor: 140 endpoints, each with its
  parameter list (wire name, type symbol, ``acceptsUndefined``) and result.
* ``Protocol/schemas/*.json`` — one JSON Schema per named type symbol.

Outputs (written, re-runnable, deterministic):

* ``Sources/DSHRemoteKit/Generated/*.swift`` — ``Codable``/``Sendable`` Swift 6
  types, one file per generated schema, plus the per-endpoint argument and
  response types and a small support file.
* ``Protocol/examples/*.json`` — one example instance per generated schema,
  built by the same walk that emits the types, so decode coverage is mechanical
  instead of hand-written.
* ``Protocol/examples/manifest.json`` — the index: every endpoint kept, every
  generated declaration with its example pointer, its schema-required JSON
  pointers, the mutation a test must make to prove the type is not vacuous, and
  a SHA-256 of every generated file.
* ``Tests/DSHRemoteKitTests/GeneratedExampleRegistry.swift`` — the generated
  bridge from manifest entries to concrete Swift types (a registry has to name
  types statically, so it is generated rather than hand-maintained).

Run ``python3 Tools/generate-models.py`` to write, ``--check`` to verify that
what is on disk is exactly what would be written, and ``--report`` to print the
inventory without touching anything.

Standard library only. No network. The schemas are read as data and nothing in
the bundle is evaluated.

DECISIONS (every one of these is a judgement call, not a fact in the schema):

1.  ``{"type":"number"}`` becomes ``Int64``. Every numeric field on this
    surface is a counter, an epoch-millisecond stamp, a byte count or a seq,
    and the hand-written models in ``Sources/DSHRemoteKit/Models`` already chose
    ``Int64`` for the same fields. A genuinely fractional host value would fail
    to decode.
2.  ``{"const": c}`` on its own becomes the primitive type of ``c``
    (``String``/``Bool``/``Int64``); the literal is not enforced by the
    generated decoder. Literal enforcement lives in the discriminated-union
    decoder, which switches on the very key the const pins.
3.  A required key whose type admits JSON ``null`` is emitted as ``T?``.
    Swift's synthesised ``init(from:)`` uses ``decodeIfPresent`` for optionals,
    so absence is tolerated for that key even though the schema marks it
    required. The manifest records enforcement as the generated code has it,
    not as the schema states it.
4.  ``record(string(), V)`` (the DSL's open record) is translated to
    ``[String: V]``; an ``intersection(object({...}), record(...))`` becomes a
    struct with an ``additionalProperties`` catch-all, decoded explicitly.
5.  String ``const`` unions become open enums whose catch-all case is
    ``unrecognized(_:)``. ``unknown`` is a real wire value in at least one of
    the unions on this surface, so it cannot be the catch-all name.
6.  Discriminated object unions become enums with associated values, selected
    by the member's string ``const`` property (``type`` first, then ``kind``).
    An unrecognised discriminator decodes to ``unrecognized(type:value:)``
    rather than failing (SPEC §5). A missing discriminator fails: the union
    cannot be classified at all.
7.  Examples carry every declared property, not only the required ones, plus one
    unnamed key in each open record. A strictly-minimal instance of an
    all-optional object would be ``{}`` and would exercise nothing.
8.  Names come from the ``typeSymbol`` alone: ``@scope/pkg#a/b:c`` is
    ``ABC``, a plain ``@scope/pkg#Name`` is ``Name``. Inline declarations append
    the PascalCased JSON path tokens from the schema root (``Item`` for array
    elements, the const value for union members, ``AdditionalProperty`` for a
    record's value type).
"""

