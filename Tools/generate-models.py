def build():
    with open(ENDPOINTS, "r", encoding="utf-8") as handle:
        descriptors = json.load(handle)
    by_key = {
        endpoint["namespace"] + "/" + endpoint["method"]: endpoint
        for endpoint in descriptors["endpoints"]
    }
    missing = sorted(set(V1_ENDPOINTS) - set(by_key))
    if missing:
        raise SystemExit(f"V1 endpoints missing from endpoints.json: {missing}")
    selected = [by_key[key] for key in sorted(V1_ENDPOINTS)]

    gen = Generator()

    schema_rels = set()
    for endpoint in selected:
        for parameter in endpoint["parameters"]:
            schema_rels.add(parameter["schema"])
        schema_rels.add(endpoint["result"]["schema"])

    excluded: list[dict] = []
    generated_schemas: list[str] = []
    for schema_rel in sorted(schema_rels):
        stem = schema_stem(schema_rel)
        if stem in EXCLUDED_SCHEMAS:
            swift, reason = EXCLUDED_SCHEMAS[stem]
            excluded.append({"schema": schema_rel, "swiftType": swift, "reason": reason})
            continue
        gen.generate_schema(schema_rel, gen.load(schema_rel))
        generated_schemas.append(schema_rel)

    endpoints = []
    for endpoint in selected:
        key = endpoint["namespace"] + "/" + endpoint["method"]
        namespace = endpoint["namespace"]
        method = endpoint["method"]

        result_schema = endpoint["result"]["schema"]
        result_stem = schema_stem(result_schema)
        if result_stem in EXCLUDED_SCHEMAS:
            response_target = EXCLUDED_SCHEMAS[result_stem][0]
            response_nullable = False
        else:
            response_target = gen.examples[result_schema]["top"]
            response_nullable = gen.examples[result_schema]["nullable"]

        parameters = []
        for parameter in endpoint["parameters"]:
            schema_rel = parameter["schema"]
            swift_type = gen.examples[schema_rel]["top"]
            wire = parameter["wire"]
            parameters.append(
                {
                    "wire": wire,
                    "swiftName": camel(wire.lstrip("_") or wire),
                    "typeSymbol": parameter["typeSymbol"],
                    "swiftType": swift_type,
                    "schema": schema_rel,
                    "acceptsUndefined": bool(parameter.get("acceptsUndefined")),
                    "source": parameter.get("source"),
                }
            )

        endpoints.append(
            {
                "method": key,
                "namespace": namespace,
                "name": method,
                "mode": endpoint.get("mode", "unary"),
                "httpPath": endpoint.get("httpPath"),
                "group": V1_ENDPOINTS[key],
                "argumentsType": endpoint_type_name(namespace, method, "Arguments"),
                "responseType": endpoint_type_name(namespace, method, "Response"),
                "responseTarget": response_target,
                "responseAlias": response_target
                + (
                    "?"
                    if response_nullable or bool(endpoint["result"].get("mayBeAbsent"))
                    else ""
                ),
                "responseNullable": response_nullable,
                "responseMayBeAbsent": bool(endpoint["result"].get("mayBeAbsent")),
                "parameters": parameters,
                "resultSchema": result_schema,
                "resultTypeSymbol": endpoint["result"]["typeSymbol"],
            }
        )

    return gen, endpoints, excluded, generated_schemas, descriptors


def swift_endpoint_file(endpoints) -> str:
    lines = [HEADER.rstrip("\n"), "import Foundation", ""]
    lines.append(
        doc_comment(
            [
                "Per-endpoint argument and response types for the V1 surface.",
                "",
                "`Arguments` is exactly the object the gateway expects under `payload.args` "
                "(SPEC §6.2);",
                "`Response` names the type the envelope's `result.value` decodes into.",
                "Generated from Protocol/endpoints.json — the wire parameter names are the "
                "descriptor's, verbatim.",
            ]
        )
    )
    lines.append("")
    for entry in endpoints:
        lines.append(f"// MARK: - {entry['method']} ({entry['mode']})")
        lines.append("")
        doc = [
            f"`{entry['method']}` — `POST {entry['httpPath']}`.",
            f"Group: {entry['group']}. Mode: `{entry['mode']}`.",
        ]
        doc.append("")
        if entry["parameters"]:
            doc.append(
                "Wire parameters: "
                + ", ".join(f"`{p['wire']}`" for p in entry["parameters"])
                + "."
            )
        else:
            doc.append("No wire parameters; the argument object is empty.")
        if entry["responseMayBeAbsent"]:
            doc.append("")
            doc.append(
                "The descriptor marks this result `_undefined()`-optional, so a successful "
                "envelope may"
            )
            doc.append(
                "carry no `value` key at all and the response alias keeps the `?` "
                "(Protocol/README.md)."
            )
        if entry["responseNullable"]:
            doc.append("")
            doc.append(
                "The result schema also admits JSON `null` (a `literal(null)` union member), "
                "so the"
            )
            doc.append("alias is optional for that reason as well.")
        doc.append(f"Result type symbol: `{entry['resultTypeSymbol']}`.")
        lines.append(doc_comment(doc))

        parameters = entry["parameters"]
        if not parameters:
            lines.append(f"public typealias {entry['argumentsType']} = RPCEmptyRequest")
        else:
            lines.append(
                f"public struct {entry['argumentsType']}: Codable, Sendable, Hashable {{"
            )
            for parameter in parameters:
                type_expr = parameter["swiftType"] + (
                    "?" if parameter["acceptsUndefined"] else ""
                )
                lines.append(
                    f"    public var {swift_ident(parameter['swiftName'])}: {type_expr}"
                )
            if any(p["swiftName"] != p["wire"] for p in parameters):
                lines.append("")
                lines.append("    enum CodingKeys: String, CodingKey {")
                for parameter in parameters:
                    lines.append(
                        f"        case {swift_ident(parameter['swiftName'])} = "
                        f"{json_string(parameter['wire'])}"
                    )
                lines.append("    }")
            lines.append("")
            lines.append("    public init(")
            for index, parameter in enumerate(parameters):
                type_expr = parameter["swiftType"] + (
                    "?" if parameter["acceptsUndefined"] else ""
                )
                default = " = nil" if parameter["acceptsUndefined"] else ""
                comma = "," if index < len(parameters) - 1 else ""
                lines.append(
                    f"        {swift_ident(parameter['swiftName'])}: {type_expr}"
                    f"{default}{comma}"
                )
            lines.append("    ) {")
            for parameter in parameters:
                ident = swift_ident(parameter["swiftName"])
                lines.append(f"        self.{ident} = {ident}")
            lines.append("    }")
            lines.append("}")

        response = entry["responseTarget"]
        if entry["responseNullable"] or entry["responseMayBeAbsent"]:
            response += "?"
        lines.append(f"public typealias {entry['responseType']} = {response}")
        lines.append("")
    return "\n".join(lines) + "\n"


def render_registry(models) -> str:
    lines = [HEADER.rstrip("\n"), "import Foundation", "import DSHRemoteKit", ""]
    lines.append(
        doc_comment(
            [
                "The bridge from Protocol/examples/manifest.json to concrete Swift types.",
                "",
                "A registry has to name types statically, so it is generated in the same pass "
                "as the types",
                "it names: a rename or a dropped type follows through instead of silently "
                "losing coverage.",
                "GeneratedModelTests asserts this file and the manifest agree, so neither can "
                "drift alone.",
            ]
        )
    )
    lines.append("")
    lines.append("/// How a test must break the example so the decode has to fail.")
    lines.append("enum GeneratedMutation: Sendable, Equatable {")
    lines.append("    /// No enforced required key and no primitive leaf: the reason says why.")
    lines.append("    case none(String)")
    lines.append("    /// Delete the value at `pointer`, a JSON Pointer into the example.")
    lines.append("    case delete(pointer: String)")
    lines.append("    /// Replace the value at `pointer` with the JSON document `json`.")
    lines.append("    case replace(pointer: String, json: String)")
    lines.append("}")
    lines.append("")
    lines.append("/// One generated declaration plus the example that must decode into it.")
    lines.append("struct GeneratedModelCase: Sendable {")
    lines.append("    let swiftType: String")
    lines.append("    let kind: String")
    lines.append("    let typeSymbol: String")
    lines.append("    let schema: String")
    lines.append("    let exampleFile: String")
    lines.append("    /// JSON Pointer into that file, or nil when the example instance does")
    lines.append("    /// not reach this declaration (a union alternative it does not take).")
    lines.append("    let examplePointer: String?")
    lines.append("    /// This declaration's own example, as a JSON document.")
    lines.append("    let exampleJSON: String")
    lines.append("    let requiredPointers: [String]")
    lines.append("    let mutation: GeneratedMutation")
    lines.append("    let decode: @Sendable (Data) throws -> Void")
    lines.append("}")
    lines.append("")
    lines.append("/// Every generated declaration, in manifest order.")
    lines.append("func generatedModelCases() -> [GeneratedModelCase] {")
    lines.append("    var cases: [GeneratedModelCase] = []")
    for model in models:
        mutation = model["mutation"]
        if mutation["op"] == "delete":
            mutation_swift = (
                f"GeneratedMutation.delete(pointer: {json_string(mutation['pointer'])})"
            )
        elif mutation["op"] == "replace":
            payload = json.dumps(mutation["value"], ensure_ascii=False)
            mutation_swift = (
                f"GeneratedMutation.replace(pointer: {json_string(mutation['pointer'])}, "
                f"json: {json_string(payload)})"
            )
        else:
            mutation_swift = (
                'GeneratedMutation.none("no enforced required key and no primitive leaf '
                'in the example")'
            )
        required = ", ".join(json_string(p) for p in model["requiredPointers"])
        lines.append("    cases.append(GeneratedModelCase(")
        lines.append(f"        swiftType: {json_string(model['swiftType'])},")
        lines.append(f"        kind: {json_string(model['kind'])},")
        lines.append(f"        typeSymbol: {json_string(model['typeSymbol'])},")
        lines.append(f"        schema: {json_string(model['schema'])},")
        lines.append(f"        exampleFile: {json_string(model['exampleFile'])},")
        pointer = model["examplePointer"]
        pointer_swift = "nil" if pointer is None else json_string(pointer)
        lines.append(f"        examplePointer: {pointer_swift},")
        document = json.dumps(
            model["example"], separators=(",", ":"), ensure_ascii=False
        )
        lines.append(f"        exampleJSON: {json_string(document)},")
        lines.append(f"        requiredPointers: [{required}],")
        lines.append(f"        mutation: {mutation_swift},")
        lines.append("        decode: { data in")
        lines.append(
            f"            _ = try JSONDecoder().decode({model['swiftType']}.self, from: data)"
        )
        lines.append("        }")
        lines.append("    ))")
    lines.append("    return cases")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_files(gen, endpoints, excluded, generated_schemas, descriptors):
    files: dict[str, str] = {}

    for top in sorted(gen.decls):
        body = [HEADER.rstrip("\n"), "import Foundation", ""]
        body.append(
            doc_comment(
                [
                    f"Every type generated from `Protocol/schemas` for `{top}`.",
                    "",
                    "Each declaration is decode-tested against an example in "
                    "`Protocol/examples`;",
                    "see `Protocol/examples/manifest.json`.",
                ]
            )
        )
        body.append("")
        for decl in gen.decls[top]:
            body.append(decl["swift"])
        files[f"Sources/DSHRemoteKit/Generated/{top}.swift"] = "\n".join(body)

    files["Sources/DSHRemoteKit/Generated/Endpoints.swift"] = swift_endpoint_file(endpoints)
    if gen.support_needed:
        body = [HEADER.rstrip("\n"), "import Foundation", ""]
        body.append(doc_comment(["Support types the generated DTOs depend on."]))
        body.append("")
        for name in sorted(gen.support_needed):
            body.append(SUPPORT_TYPES[name])
        files["Sources/DSHRemoteKit/Generated/Support.swift"] = "\n".join(body)

    for schema_rel in sorted(gen.examples):
        info = gen.examples[schema_rel]
        stem = schema_stem(schema_rel)
        files[f"Protocol/examples/{stem}.json"] = (
            json.dumps(info["example"].value, indent=2, ensure_ascii=False) + "\n"
        )

    for entry in endpoints:
        args = {}
        for parameter in entry["parameters"]:
            schema_rel = parameter["schema"]
            if schema_rel in gen.examples:
                args[parameter["wire"]] = gen.examples[schema_rel]["example"].value
        name = entry["method"].replace("/", ".")
        files[f"Protocol/examples/endpoints/{name}.args.json"] = (
            json.dumps(args, indent=2, ensure_ascii=False) + "\n"
        )

    hashes = {
        path: hashlib.sha256(content.encode("utf-8")).hexdigest()
        for path, content in sorted(files.items())
    }

    manifest = {
        "note": (
            "Generated by Tools/generate-models.py — not fixtures. Every *.json here other "
            "than this manifest is one example instance of the schema with the same file "
            "name stem: every declared property present, one element per array, one unnamed "
            "key per open record. 'requiredPointers' are the schema-required keys the "
            "example carries; 'mutation' is the edit the decode test makes so the generated "
            "decoder has to fail."
        ),
        "generatedBy": "Tools/generate-models.py",
        "harnessVersion": descriptors["source"]["harnessVersion"],
        "hostProtocolVersion": descriptors["source"]["hostProtocolVersion"],
        "endpointGroups": ENDPOINT_GROUPS,
        "endpoints": endpoints,
        "schemas": [
            {
                "schema": schema_rel,
                "example": f"examples/{schema_stem(schema_rel)}.json",
                "rootType": gen.examples[schema_rel]["top"],
                "nullable": gen.examples[schema_rel]["nullable"],
                "typeSymbol": gen.examples[schema_rel]["symbol"],
            }
            for schema_rel in generated_schemas
        ],
        "models": [
            {key: value for key, value in model.items() if key != "example"}
            for model in gen.manifest_models
        ],
        "excludedSchemas": excluded,
        "generatedSchemas": generated_schemas,
        "warnings": sorted(gen.warnings),
        "fileHashes": hashes,
    }
    files["Protocol/examples/manifest.json"] = (
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    )
    files["Tests/DSHRemoteKitTests/GeneratedExampleRegistry.swift"] = render_registry(
        gen.manifest_models
    )
    return files


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Generate the DSH V1 typed models.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify that the files on disk match what would be written",
    )
    parser.add_argument(
        "--report",
        action="store_true",
        help="print the inventory and exit without writing",
    )
    args = parser.parse_args(argv)

    try:
        gen, endpoints, excluded, generated_schemas, descriptors = build()
    except SchemaError as error:
        print(f"generation failed: {error}", file=sys.stderr)
        return 1

    if args.report:
        print(f"endpoints: {len(endpoints)}")
        for entry in endpoints:
            print(
                f"  {entry['method']:34s} {entry['mode']:7s} "
                f"{entry['argumentsType']} -> {entry['responseType']}"
            )
        print(f"generated schemas: {len(generated_schemas)}")
        print(f"excluded schemas: {len(excluded)}")
        print(f"generated declarations: {len(gen.manifest_models)}")
        kinds: dict[str, int] = {}
        for model in gen.manifest_models:
            kinds[model["kind"]] = kinds.get(model["kind"], 0) + 1
        print(f"  {kinds}")
        ops: dict[str, int] = {}
        for model in gen.manifest_models:
            op = model["mutation"]["op"]
            ops[op] = ops.get(op, 0) + 1
        print(f"  mutations: {ops}")
        print(f"support types: {sorted(gen.support_needed)}")
        for warning in gen.warnings:
            print(f"warning: {warning}")
        return 0

    files = render_files(gen, endpoints, excluded, generated_schemas, descriptors)

    if args.check:
        stale = []
        for path, content in sorted(files.items()):
            full = os.path.join(ROOT, path)
            if not os.path.exists(full):
                stale.append(f"missing: {path}")
                continue
            with open(full, "r", encoding="utf-8") as handle:
                if handle.read() != content:
                    stale.append(f"differs: {path}")
        for path in sorted(known_generated_paths()):
            if path not in files:
                stale.append(f"stale: {path}")
        for line in stale:
            print(line, file=sys.stderr)
        if stale:
            print(f"{len(stale)} file(s) out of date", file=sys.stderr)
            return 1
        print(f"up to date: {len(files)} file(s)")
        return 0

    for path, content in sorted(files.items()):
        full = os.path.join(ROOT, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8") as handle:
            handle.write(content)
    for path in sorted(known_generated_paths() - set(files)):
        os.remove(os.path.join(ROOT, path))
        print(f"removed stale {path}")

    print(f"wrote {len(files)} file(s)")
    print(f"  endpoints: {len(endpoints)}")
    print(f"  generated schemas: {len(generated_schemas)}")
    print(f"  generated declarations: {len(gen.manifest_models)}")
    for warning in gen.warnings:
        print(f"warning: {warning}")
    return 0


def known_generated_paths() -> set[str]:
    """Files this tool owns, so a removed schema does not leave a stale twin."""
    paths = set()
    for directory, suffix in (
        (os.path.join(ROOT, "Sources", "DSHRemoteKit", "Generated"), ".swift"),
        (os.path.join(PROTOCOL, "examples"), ".json"),
        (os.path.join(PROTOCOL, "examples", "endpoints"), ".json"),
    ):
        if not os.path.isdir(directory):
            continue
        for name in os.listdir(directory):
            if name.endswith(suffix):
                paths.add(os.path.relpath(os.path.join(directory, name), ROOT))
    return paths


if __name__ == "__main__":
    sys.exit(main())
