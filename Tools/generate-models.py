class Example:
    """The example instance for one schema node, plus the metadata a
    mutation-based decode test needs."""

    __slots__ = ("value", "children", "strict", "disjoint", "pointer")

    def __init__(self, value, children=None, strict=False, disjoint=None, pointer=""):
        self.value = value
        # (json_segment, name_token, child, enforced). `json_segment` is the key
        # or index reaching the child in the example document, or None where the
        # child shares the parent's JSON location (a union member). `name_token`
        # is the token the declaration's name path uses.
        self.children = children or []
        self.strict = strict
        self.disjoint = disjoint
        self.pointer = pointer


def join_pointer(base: str, segment) -> str:
    text = str(segment).replace("~", "~0").replace("/", "~1")
    return f"{base}/{text}"


def relative_pointer(pointer: str, base: str) -> str:
    """A JSON Pointer expressed relative to the declaration's own example node."""
    if base == "":
        return pointer
    if pointer == base:
        return ""
    if pointer.startswith(base + "/"):
        return pointer[len(base):]
    return pointer


def required_pointers(example: Example, base: str) -> list[str]:
    """Every schema-required key present in the example, in example order,
    each as a JSON Pointer relative to `base` (the declaration's own node)."""
    out: list[str] = []

    def walk(node: Example):
        for _segment, _token, child, required in node.children:
            if required:
                out.append(relative_pointer(child.pointer, base))
            walk(child)

    walk(example)
    return out


def find_mutation(example: Example, base: str) -> dict:
    """The cheapest edit that must make the generated decoder fail.

    Preference order, breadth first so the shallowest wins:

    1. delete a key the schema marks required *and* the generated Swift code
       actually enforces (a required key typed ``T?`` decodes through
       ``decodeIfPresent``, so its absence is tolerated and it is skipped);
    2. replace a primitive leaf with a value of a disjoint JSON type.
    """
    queue = [example]
    while queue:
        node = queue.pop(0)
        for _segment, _token, child, required in node.children:
            if required and child.strict:
                return {"op": "delete", "pointer": relative_pointer(child.pointer, base)}
            if child.children:
                queue.append(child)
    queue = [example]
    while queue:
        node = queue.pop(0)
        if not node.children and node.strict and node.disjoint is not None:
            return {
                "op": "replace",
                "pointer": relative_pointer(node.pointer, base),
                "value": node.disjoint,
            }
        for _segment, _token, child, _required in node.children:
            queue.append(child)
    return {"op": "none"}


