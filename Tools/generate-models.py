def pascal(text: str) -> str:
    parts = [p for p in re.split(r"[^0-9A-Za-z]+", text) if p]
    return "".join(p[:1].upper() + p[1:] for p in parts)


def camel(text: str) -> str:
    p = pascal(text)
    if not p:
        return text
    return p[:1].lower() + p[1:]


def swift_ident(name: str) -> str:
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def swift_name_for_symbol(symbol: str) -> str:
    """Stable Swift type name from a descriptor `typeSymbol`.

    ``@scope/pkg#a/b:c`` -> ``ABC`` (from ``a``/``b``/``c``);
    ``@scope/pkg#Name`` -> ``Name``. The package segment is only used when the
    symbol path alone yields no identifier.
    """
    spec = symbol.split("/", 1)[1] if symbol.startswith("@") else symbol
    package, _, rest = spec.partition("#")
    tokens = [p for p in re.split(r"[/:]+", rest) if p]
    name = "".join(pascal(t) for t in tokens) or pascal(package)
    return name


def endpoint_type_name(namespace: str, method: str, suffix: str) -> str:
    return pascal(namespace) + pascal(method) + suffix


